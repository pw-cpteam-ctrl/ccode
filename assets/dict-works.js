/* 일본어 문자열(폴더명·상품명 등) 안에서 작품을 찾아 한국 정식명을 돌려준다.
   긴 키부터 검사하는 이유: 'ガンダム'가 '機動戦士ガンダムSEED'보다 먼저 걸리면
   SEED 상품이 전부 그냥 '기동전사 건담'으로 잡혀버린다. */
function findSharedWork(text) {
  const t = String(text || '');
  if (!t) return null;
  let best = null;
  for (const jp of Object.keys(SHARED_WORKS)) {
    if (t.includes(jp) && (!best || jp.length > best.length)) best = jp;
  }
  return best ? { jp: best, ko: SHARED_WORKS[best] } : null;
}
